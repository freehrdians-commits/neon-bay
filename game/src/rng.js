// Seeded random numbers for Neon Bay: one small generator (mulberry32) keeps
// the city, traffic and pedestrians identical for a given ?seed=, so a
// screenshot or a playtest can be reproduced exactly.
export function makeRng(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function range(rng, min, max) {
  return min + rng() * (max - min);
}

export function int(rng, min, max) {
  return Math.floor(range(rng, min, max + 1));
}

export function pick(rng, list) {
  return list[Math.floor(rng() * list.length)];
}

export function chance(rng, p) {
  return rng() < p;
}

// A roughly bell-shaped draw in [-1, 1], from the seeded generator — for
// spreads that cluster near the middle instead of scattering flat.
export function gauss(rng) {
  return (rng() + rng() + rng() - 1.5) / 1.5;
}

// Pick one entry from [{ value, weight }] in proportion to its weight.
export function weightedPick(rng, entries) {
  let total = 0;
  for (const e of entries) total += e.weight;
  let roll = rng() * total;
  for (const e of entries) {
    roll -= e.weight;
    if (roll <= 0) return e.value;
  }
  return entries[entries.length - 1].value;
}

// A shuffled copy of an array, using the seeded generator.
export function shuffle(rng, list) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}
